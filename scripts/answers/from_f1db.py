#!/usr/bin/env python3
"""
Write every Formula 1 World Championship race starter from f1db (CC BY 4.0, github.com/f1db/f1db) into
scripts/answers/lists/f1-driver.f1db.txt (then run build.py).

    git clone --depth 1 https://github.com/f1db/f1db /tmp/f1db
    python3 scripts/answers/from_f1db.py /tmp/f1db

Only drivers who appear in a championship race result are taken (not practice-only or reserve drivers). Each is shown
as their usual name ("Lewis Hamilton") with their full name as an accepted spelling. Credit: F1DB, CC BY 4.0.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'lists', 'f1-driver.f1db.txt')


def field(text, key):
    m = re.search(rf'^{key}: ?(.*)$', text, re.M)
    v = m.group(1).strip().strip('"') if m else ''
    return v


def main(base):
    data = os.path.join(base, 'src', 'data')
    raced = set()
    for root, _, files in os.walk(os.path.join(data, 'seasons')):
        if 'race-results.yml' in files:
            raced |= set(re.findall(r'driverId: ([a-z0-9-]+)', open(os.path.join(root, 'race-results.yml'), encoding='utf-8').read()))
    rows = []
    for f in sorted(os.listdir(os.path.join(data, 'drivers'))):
        did = f[:-4]
        if did not in raced:
            continue
        t = open(os.path.join(data, 'drivers', f), encoding='utf-8').read()
        name, full = field(t, 'name'), field(t, 'fullName')
        al = [a for a in [full] if a and a.lower() != name.lower()]
        rows.append(name + ('|' + ';'.join(al) if al else ''))
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('# F1DB (github.com/f1db/f1db, CC BY 4.0), generated by scripts/answers/from_f1db.py\n')
        fh.write('\n'.join(rows) + '\n')
    print(f'f1-driver: {len(rows)} of {len(raced)} race starters')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/f1db')
