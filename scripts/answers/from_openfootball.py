#!/usr/bin/env python3
"""
Write football clubs from openfootball/clubs (CC0, github.com/openfootball/clubs) into
scripts/answers/lists/football-club.openfootball.txt (then run build.py).

    git clone --depth 1 https://github.com/openfootball/clubs /tmp/clubs
    python3 scripts/answers/from_openfootball.py /tmp/clubs

Each club becomes one answer, shown by its everyday name ("Arsenal", not "Arsenal FC"), with its other names as
accepted spellings. Only clubs with a known founding year or ground are taken, which keeps out the thinnest entries.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'lists', 'football-club.openfootball.txt')
AFFIX = re.compile(r'^(?:(?:A\.?F\.?C\.?|F\.?C\.?|C\.?F\.?|S\.?C\.?|A\.?C\.?|S\.?S\.?C?\.?|U\.?S\.?|C\.?D\.?|S\.?V\.?|V\.?f\.?[BL]\.?|T\.?S\.?V\.?|1\.\s*FC|K\.?\s*R\.?\s*C\.?|R\.?\s*S\.?\s*C\.?|C\.?A\.?|S\.?K\.?|I\.?F\.?K\.?|B\.?K\.?|F\.?K\.?|N\.?K\.?|H\.?N\.?K\.?|G\.?D\.?|S\.?D\.?|A\.?S\.?|R\.?C\.?|O\.?S\.?C\.?|P\.?F\.?C\.?)\s+)|'
                   r'(?:\s+(?:A\.?F\.?C\.?|F\.?C\.?|C\.?F\.?|S\.?C\.?|A\.?C\.?|S\.?K\.?|I\.?F\.?|B\.?K\.?|F\.?K\.?|C\.?D\.?|S\.?V\.?|S\.?D\.?|F\.?F\.?|IF|BK|FF))$')


# One-word names that could be many clubs: never accepted as a spelling of a single one.
GENERIC = {'albion', 'wanderers', 'rangers', 'rovers', 'united', 'city', 'town', 'county', 'athletic', 'athletico', 'real',
           'sporting', 'nacional', 'national', 'municipal', 'dynamo', 'dinamo', 'spartak', 'lokomotiv', 'olympic', 'olympique',
           'racing', 'union', 'sport', 'club', 'spartans', 'universidad', 'independiente', 'deportivo', 'atletico', 'atlético',
           'internacional', 'inter', 'juventud', 'progreso', 'liverpool', 'everton', 'arsenal', 'celtic', 'santos', 'america',
           'américa', 'alianza', 'unión', 'estudiantes', 'olimpia', 'cerro', 'defensor', 'river', 'wolves', 'saints', 'villa'}


def everyday(name, aliases):
    """The shortest sensible form: 'Arsenal FC' → 'Arsenal'; keeps the full form as an alias."""
    bare = AFFIX.sub('', name).strip() or name
    cands = [bare] + [a for a in aliases if len(a) >= 4 and not re.search(r'\.\s*$|\b[A-Z]\.$', a)]
    # Prefer the bare official name unless an alias is clearly the everyday one and contains it.
    return bare


def parse(path):
    clubs, cur = [], None
    for raw in open(path, encoding='utf-8'):
        line = raw.split('#')[0].rstrip()
        if not line.strip() or line.lstrip().startswith(('=', '[')):
            continue
        if line.lstrip().startswith('|'):
            if cur:
                cur[1].extend(a.strip() for a in line.split('|') if a.strip())
            continue
        if raw[:1].isspace():
            continue
        parts = [p.strip() for p in line.split(',')]
        name = parts[0]
        notable = any(re.fullmatch(r'\d{4}', p) for p in parts[1:]) or '@' in line
        cur = [name, [], notable]
        clubs.append(cur)
    return clubs


def main(base):
    rows, seen = [], set()
    for root, _, files in os.walk(base):
        for f in sorted(files):
            if not f.endswith('.clubs.txt'):
                continue
            for name, aliases, notable in parse(os.path.join(root, f)):
                if not notable or re.search(r'\b(II|B|U\d\d|Reserves?|Youth|Women|Ladies|Juniors?)\b', name):
                    continue
                show = everyday(name, aliases)
                if len(show) < 3 or show.lower() in seen:
                    continue
                seen.add(show.lower())
                aliases = [re.sub(r'\s*\[[a-z]{2}\]', '', a).strip(' ,') for a in aliases]
                al = [a for a in dict.fromkeys([name] + aliases) if a.lower() != show.lower() and len(a) >= 3
                      and not re.search(r'\.$', a) and a.lower() not in GENERIC]
                rows.append(show + ('|' + ';'.join(a.replace('|', ' ').replace(';', ',') for a in al) if al else ''))
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('# openfootball/clubs (CC0, github.com/openfootball/clubs), generated by scripts/answers/from_openfootball.py\n')
        fh.write('\n'.join(rows) + '\n')
    print(f'football-club: {len(rows)}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/clubs')
