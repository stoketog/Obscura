def write(pid, names, source):
    seen, rows = set(), []
    for n in names:
        n = re.sub(r'\s+', ' ', n).strip()
        k = n.lower()
        if n and k not in seen:
            seen.add(k)
            rows.append(n)
    with open(os.path.join(LISTS, f'{pid}.data.txt'), 'w', encoding='utf-8') as f:
        f.write(f'# {source}\n# Generated by scripts/answers/fetch_sources.py\n')
        f.write('\n'.join(rows) + '\n')
    print(f'{pid}: {len(rows)}')


def pokemon():
    url = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv'
    raw = urllib.request.urlopen(url, timeout=60).read().decode('utf-8')
    names = [r['name'] for r in csv.DictReader(io.StringIO(raw)) if r['local_language_id'] == '9']
    write('pokemon', names, 'PokeAPI pokemon_species_names.csv, English')


def cities():
    import geonamescache
    gc = geonamescache.GeonamesCache()
    continent = {c['iso']: c['continentcode'] for c in gc.get_countries().values()}
    import math
    admin = re.compile(r'\d|sector|circoscrizione|circoiscrizione|district|county|island$|territories|borough|municipality|okrug|rayon', re.I)

    def km(a, b):
        dlat = math.radians(a['latitude'] - b['latitude'])
        dlon = math.radians(a['longitude'] - b['longitude']) * math.cos(math.radians((a['latitude'] + b['latitude']) / 2))
        return 6371 * math.hypot(dlat, dlon)

    for pid, code in [('european-city', 'EU'), ('asian-city', 'AS')]:
        rows = [c for c in gc.get_cities().values() if continent.get(c['countrycode']) == code and not admin.search(c['name']) and c['name'] not in ('Pest', 'Buda', 'Saint Peters')]
        rows.sort(key=lambda c: -c['population'])
        # A place within 15 km of somewhere at least three times its size is usually a district or suburb of it.
        big = rows[:400]
        rows = [c for c in rows if not any(o is not c and o['population'] >= 3 * c['population'] and km(o, c) < 15 for o in big)]
        write(pid, [c['name'] for c in rows[:CITIES_PER_CONTINENT]], f'GeoNames cities over 15,000 people, continent {code}, biggest {CITIES_PER_CONTINENT}')
    caps = [c['capital'] for c in gc.get_countries().values() if c.get('capital') and c['capital'] not in ('East Jerusalem', 'Hong Kong', 'Macao', 'Singapore', 'Monaco', 'Vatican City')]
    write('capital-city', caps, 'GeoNames country and territory capitals')


def corpora(root):
    def load(path, key):
        return json.load(open(os.path.join(root, 'data', path), encoding='utf-8'))[key]

    clade = re.compile(r'(ia|idae|inae|oidea|ae|formes|poda|pods)$', re.I)
    write('dinosaur', [d for d in load('animals/dinosaurs.json', 'dinosaurs') if not clade.search(d) and ' ' not in d and d.lower() not in DINO_DROP], 'dariusk/corpora dinosaurs.json (genera only)')
    write('dog-breed', load('animals/dogs.json', 'dogs'), 'dariusk/corpora dogs.json')
    bad = re.compile(r'synthetic|coated|imitation|treated|glass|plastic|\d', re.I)
    write('gemstone', [g[0].upper() + g[1:] for g in load('materials/gemstones.json', 'gemstones') if not bad.search(g) and g.lower() not in GEM_DROP], 'dariusk/corpora gemstones.json')
    write('fabric', [f[0].upper() + f[1:] for f in load('materials/fabrics.json', 'fabrics') if f.lower() not in FABRIC_DROP], 'dariusk/corpora fabrics.json')
    write('music-genre', [g for g in load('music/genres.json', 'genres') if '/' not in g], 'dariusk/corpora genres.json')
    write('sport', [x for x in load('sports/sports.json', 'sports') if x.lower() not in SPORT_DROP], 'dariusk/corpora sports.json (games, events and headings removed)')
    write('boardgame', [g for g in load('games/board_games.json', 'games') if not g.endswith('?')], 'dariusk/corpora board_games.json')
    write('scientist', [x for x in load('humans/scientists.json', 'scientists') if x.lower() not in SCIENTIST_DROP], 'dariusk/corpora scientists.json')
    write('job', [o[0].upper() + o[1:] for o in load('humans/occupations.json', 'occupations')], 'dariusk/corpora occupations.json')


