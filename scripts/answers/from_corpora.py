#!/usr/bin/env python3
"""
Write answer lists from dariusk/corpora (CC0) into scripts/answers/lists/<prompt-id>.corpora.txt (then run build.py).

    git clone --depth 1 https://github.com/dariusk/corpora /tmp/corpora
    python3 scripts/answers/from_corpora.py /tmp/corpora

Uses: the Wikipedia list of colours, Crayola and web colour names; the Wikipedia list of cheeses (curds.json, minus
the fermented dairy that is not cheese); programming languages; herbs and spices; IBA cocktails; fruits; breads;
car makers; mythical monsters; Norse, Egyptian, Greek and Roman gods; instruments; clothing; kitchen appliances.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LISTS = os.path.join(HERE, 'lists')

# Fermented dairy in the Wikipedia list that is not cheese (exact names, so real cheeses like Butterkäse stay in).
NOT_CHEESE = {'butter', 'chortan', 'clotted cream', 'dahi', 'ghee', 'greek yogurt', 'kajmak', 'kaymak', 'kashk', 'kefir',
              'khoa', 'bhuna khoa', 'kiselo mlyako', 'kulfi', 'milk skin', 'minyak samin', 'qatiq', 'rømme', 'shrikhand',
              'smetana', 'sour cream', 'strained yogurt', 'zsendice', 'crème fraîche', 'creme fraiche', 'tvaroh', 'uova di bufala',
              'yogurt', 'yoghurt', 'ayran', 'doogh', 'buttermilk', 'smen', 'katyk', 'ryazhenka', 'varenets', 'prostokvasha',
              'matsoni', 'viili', 'filmjölk', 'kumis', 'airag', 'clabber', 'junket', 'quark'}
KITCHEN = re.compile(r"\b(kettle|toaster|oven|microwave|fridge|refrigerator|freezer|dishwasher|blender|mixer|processor|"
                     r"juicer|grill|griddle|cooker|fryer|maker|grinder|hob|stove|range|slicer|warmer|steamer|"
                     r"dehydrator|roaster|percolator|kitchen|waffle|sandwich|popcorn|ice ?cream|bread|rice|egg|"
                     r"pressure|slow|sous|extractor|hood|can opener|knife sharpener|scale)\b", re.I)


def load(base, rel):
    return json.load(open(os.path.join(base, 'data', rel), encoding='utf-8'))


def camel(s):
    return re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', s)


def tidy(s):
    s = re.sub(r'\s+', ' ', s).strip()
    s = re.sub(r'\s*\((programming language|apple programming language|[^)]*language[^)]*)\)$', '', s, flags=re.I)
    return s[:1].upper() + s[1:] if s else s


def write(pid, names, source):
    seen, rows = set(), []
    for n in names:
        n = tidy(n)
        if n and n.lower() not in seen and len(n) <= 48:
            seen.add(n.lower())
            rows.append(n)
    with open(os.path.join(LISTS, f'{pid}.corpora.txt'), 'w', encoding='utf-8') as f:
        f.write(f'# {source} (github.com/dariusk/corpora, CC0)\n# Generated by scripts/answers/from_corpora.py\n')
        f.write('\n'.join(rows) + '\n')
    print(f'{pid}: {len(rows)}')


def main(base):
    wiki = [c['name'] for c in load(base, 'colors/wikipedia.json')]
    cray = [c['color'] for c in load(base, 'colors/crayola.json')['colors']]
    web = [camel(c['color']) for c in load(base, 'colors/web_colors.json')['colors']]
    # Names that are really a brand, a code or a joke rather than a colour.
    colour_drop = re.compile(r"\b(crayola|pantone|ncs|munsell|cmyk|rgb|ryb|psychedelic|fluorescent|neon|metallic|pearl|"
                             r"web|x11|html|css|traditional|process|pigment|manatee|mountbatten|unmellow|razzle|flesh|cultured|patriarch|"
                             r"spanish|middle|dark|light|deep|pale|medium|bright|vivid)\b", re.I)
    write('colour', [c for c in wiki + cray + web if not colour_drop.search(c) and not re.search(r'[\d(#]', c) and not re.match(r'[A-Z]{2,4} ', c)],
          'Wikipedia list of colours, Crayola colours and web colour names')

    curds = load(base, 'foods/curds.json')['curds']
    write('cheese', [c for c in curds if c.strip().lower() not in NOT_CHEESE], 'Wikipedia list of cheeses')

    langs = load(base, 'technology/programming_languages.json')
    langs = langs['programming_languages'] if isinstance(langs, dict) else langs
    write('programming-language', [l for l in langs if len(l) >= 2 and not re.search(r"for Android|/|,", l)],
          'Wikipedia list of programming languages')

    hs = load(base, 'foods/herbs_n_spices.json')
    write('spice', hs['herbs'] + hs['spices'] + hs['mixtures'], 'Herbs and spices')
    write('cocktail', [c['name'] if isinstance(c, dict) else c for c in load(base, 'foods/iba_cocktails.json')['cocktails']], 'IBA official cocktails')
    write('fruit', load(base, 'foods/fruits.json')['fruits'], 'Fruits')
    write('bread', load(base, 'foods/breads_and_pastries.json')['breads'], 'Breads')
    write('car-brand', load(base, 'corporations/cars.json')['cars'], 'Car makers')
    monsters = load(base, 'mythology/monsters.json')['names'] + [m['name'] if isinstance(m, dict) else m for m in load(base, 'mythology/greek_monsters.json')['greek_monsters']]
    write('mythical', [m for m in monsters if m.lower() not in {'angel', 'homonculus', 'icthyocentaur', 'synthian dracanus'}], 'Mythical monsters')
    nd = load(base, 'mythology/norse_gods.json')['norse_deities']
    gods = [g['name'] if isinstance(g, dict) else g for g in list(nd['gods']) + list(nd.get('goddesses', []))]
    gods += list(load(base, 'mythology/egyptian_gods.json')['egyptian_gods'].keys())
    gods += [g['name'] if isinstance(g, dict) else g for g in load(base, 'mythology/roman_deities.json')['roman_deities']]
    gods += [g['name'] if isinstance(g, dict) else g for g in load(base, 'mythology/greek_gods.json')['greek_gods']]
    write('ancient-god', gods, 'Norse, Egyptian, Roman and Greek deities')
    write('instrument', load(base, 'music/instruments.json')['instruments'], 'Musical instruments')
    write('clothing', load(base, 'objects/clothing.json')['clothes'], 'Clothing types')
    write('kitchen-item', [a for a in load(base, 'technology/appliances.json')['appliances'] if KITCHEN.search(a)], 'Kitchen appliances')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/corpora')
